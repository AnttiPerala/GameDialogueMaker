// Run after editing export-templates/godot. Bundled for offline/file:// exports.
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..', 'export-templates', 'godot');
const files = {};
function walk(directory, prefix = '') {
    for (const entry of fs.readdirSync(directory, {withFileTypes: true})) {
        const name = prefix + entry.name;
        if (entry.isDirectory()) walk(path.join(directory, entry.name), name + '/');
        else files[name] = fs.readFileSync(path.join(directory, entry.name), 'utf8');
    }
}
walk(root);
fs.writeFileSync(path.join(__dirname, '..', 'js', 'godotTemplate.js'),
    '// Generated by tools/build-godot-template.js. Edit export-templates/godot instead.\n' +
    'const godotTemplate = ' + JSON.stringify(files, null, 2) + ';\n' +
    'if (typeof module !== "undefined") module.exports = godotTemplate;\n');
