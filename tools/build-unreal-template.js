// Rebuild after editing export-templates/unreal. Keeps browser exports offline.
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..', 'export-templates', 'unreal');
const files = {};
function walk(directory, prefix = '') {
    for (const entry of fs.readdirSync(directory, {withFileTypes:true})) {
        const name = prefix + entry.name;
        if (entry.isDirectory()) walk(path.join(directory, entry.name), name + '/');
        else files[name] = fs.readFileSync(path.join(directory, entry.name), 'utf8');
    }
}
walk(root);
fs.writeFileSync(path.join(__dirname, '..', 'js', 'unrealTemplate.js'),
    '// Generated by tools/build-unreal-template.js. Edit export-templates/unreal instead.\n' +
    'const unrealTemplate = ' + JSON.stringify(files, null, 2) + ';\n' +
    'if (typeof module !== "undefined") module.exports = unrealTemplate;\n');
