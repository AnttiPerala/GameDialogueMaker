// Rebuild after editing export-templates/gamemaker. Keeps browser exports offline.
const fs = require('node:fs');
const path = require('node:path');
const files = {};
function walk(directory, prefix = '') {
    for (const entry of fs.readdirSync(directory, {withFileTypes:true})) {
        const name = prefix + entry.name;
        if (entry.isDirectory()) walk(path.join(directory, entry.name), name + '/');
        else files[name] = fs.readFileSync(path.join(directory, entry.name), 'utf8');
    }
}
walk(path.join(__dirname, '..', 'export-templates', 'gamemaker'));
fs.writeFileSync(path.join(__dirname, '..', 'js', 'gameMakerTemplate.js'),
    '// Generated by tools/build-gamemaker-template.js. Edit export-templates/gamemaker instead.\n' +
    'const gameMakerTemplate = ' + JSON.stringify(files, null, 2) + ';\n' +
    'if (typeof module !== "undefined") module.exports = gameMakerTemplate;\n');
